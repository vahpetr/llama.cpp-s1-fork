// [TAG_DEEP_CKPT] a recurrent-state checkpoint that left the in-RAM list and lives in the disk cache's
// content-addressed checkpoint store (server_disk_cache), referenced by the conversation that owns it
struct server_deep_ref {
    int64_t     n_tokens = 0;
    std::string key;            // server_tokens::prefix_keys of [0, n_tokens)
    uint8_t     kind     = 0;   // DEEP_KIND_*

    static constexpr uint8_t DEEP_KIND_DEPTH  = 0; // kept by the depth schedule
    static constexpr uint8_t DEEP_KIND_ANCHOR = 1; // first checkpoint of the conversation (system prompt + tools)
    static constexpr uint8_t DEEP_KIND_BRANCH = 2; // a point a branch was taken from
    // [TAG_SEMANTIC_CKPT] (SC1) a checkpoint at a message boundary (a user turn start, the end of the system prompt or of
    //   a tool result): the newest --cache-disk-ckpt-semantic of them are kept, older ones fall back to the depth rule
    static constexpr uint8_t DEEP_KIND_SEMANTIC = 3;

    // which ref survives at one position: branch > anchor (as before) > semantic > depth (an older build orders by value and keeps
    //   every kind but depth / branch, so a semantic ref written here stays kept there: a rollback reads it)
    static int rank(uint8_t kind) {
        switch (kind) {
            case DEEP_KIND_BRANCH:   return 3;
            case DEEP_KIND_ANCHOR:   return 2;
            case DEEP_KIND_SEMANTIC: return 1;
            default:                 return 0;
        }
    }
    static const char * name(uint8_t kind) {
        switch (kind) {
            case DEEP_KIND_ANCHOR:   return "anchor";
            case DEEP_KIND_BRANCH:   return "branch";
            case DEEP_KIND_SEMANTIC: return "semantic";
            default:                 return "depth";
        }
    }
};

struct server_prompt {
    server_tokens tokens;

    std::list<common_prompt_checkpoint> checkpoints;

    std::vector<server_deep_ref> deep; // ascending n_tokens, all <= tokens.size()

    // [TAG_NONCANONICAL] the retained KV was computed with tokens that are no longer in `tokens` (context shift,
    //   n_cache_reuse shift): it is not the state of this token prefix, so it is never published (disk save, deep_put)
    bool noncanonical = false;

    // [TAG_TURN_BOUNDARY] token positions of the user-message starts of this prompt (from the task's message_spans),
    //   ascending; positions >= tokens.size() are stale (a trimmed prompt) and ignored by users_beyond(). Empty =
    //   unknown (raw /completion, a legacy snapshot, a v5 disk entry): the late-branch save rule is then inactive
    std::vector<int32_t> user_starts;

    // [TAG_PARTIAL_PROMPT] the draft side is incomplete (a legacy /slots restore brings the target state only: the
    //   draft KV restarts empty and is not rebuilt for the restored prefix); never published (disk save, deep_put)
    //   until a full recompute (n_past = 0) clears it
    bool partial = false;

    // [TAG_DRAFT_PARTIAL] the TARGET state is canonical, only the draft history lacks the rows [0, draft_gap) (an adopted
    //   target-only disk load, or an entry saved with draft_cover < n_tokens): prefix reuse, disk saves and deep
    //   checkpoints are allowed; a save records draft_cover = draft_cover_rows(). The rows appended after the load are
    //   computed by the target and caught up by the draft (decode / catch-up path), so the draft holds [draft_gap, n);
    //   a trim below draft_gap lowers it, a full recompute (n_past = 0) clears it. Distinct from `partial` (series C:
    //   the legacy /slots restore, never published)
    int32_t draft_gap = 0;

    bool draft_partial() const {
        return draft_gap > 0;
    }

    // the number of prompt rows present in the draft history
    int64_t draft_cover_rows() const {
        return std::max<int64_t>(0, (int64_t) tokens.size() - draft_gap);
    }

    // a trim of the prompt to n tokens: the draft gap cannot exceed the kept prefix
    void draft_trim(int64_t n) {
        draft_gap = (int32_t) std::max<int64_t>(0, std::min<int64_t>(draft_gap, n));
    }

    // [TAG_DISK_ADOPT] (Hermes gate Minor 2) the adopt source this state was loaded from, stamped as adopted_from on
    //   its next disk save; it lives with the prompt, so every clear / erase / invalidation / full reset drops it
    std::string adopted_from;

    void clear() {
        tokens.clear();
        checkpoints.clear();
        deep.clear();
        noncanonical = false;
        user_starts.clear();
        partial = false;
        draft_gap = 0;
        adopted_from.clear();
    }

    // [TAG_TURN_BOUNDARY] a user message of this prompt starts at or after pos: a whole later turn lies there
    bool user_start_from(int32_t pos) const {
        for (const int32_t p : user_starts) {
            if (p >= pos && p < (int32_t) tokens.size()) {
                return true;
            }
        }
        return false;
    }

    int n_tokens() const {
        return tokens.size();
    }

    server_prompt clone() const {
        return server_prompt {
            tokens.clone(),
            checkpoints,
            deep,
            noncanonical,
            user_starts,
            partial,
            draft_gap,
            adopted_from,
        };
    }
};

struct server_prompt_data {
    std::vector<uint8_t> main;
    std::vector<uint8_t> drft;
    std::vector<uint8_t> spec; // [TAG_CACHE_COMPAT2] the speculative carry (common_speculative_get_state) at save

    size_t size() const {
        return main.size() + drft.size() + spec.size();
    }
};

struct server_prompt_cache_state {
    server_prompt prompt;
    server_prompt_data data;
    std::string desc; // [TAG_CACHE_COMPAT2] the state descriptor hash of the contexts that wrote it

    size_t size() const {
        size_t res = data.size();

        for (const auto & ckpt : prompt.checkpoints) {
            res += ckpt.size();
        }

        return res;
    }
};

struct server_prompt_cache {
    server_prompt_cache(int32_t limit_size_mib, size_t limit_tokens) {
        this->limit_size   = 1024ull*1024ull*(limit_size_mib < 0 ? 0 : limit_size_mib);
        this->limit_tokens = limit_tokens;
    }

    std::list<server_prompt_cache_state> states;

    // in bytes, 0 = no limit
    size_t limit_size = 0;

    // in tokens, 0 = no limit
    size_t limit_tokens = 0;

    size_t size() const;

    size_t n_tokens() const;

    // desc: the state descriptor hash of the saving contexts (server_cache_state_desc); load() only swaps in a state
    //   whose desc equals the loading contexts' (a cheap guard, astra compat2 r2)
    server_prompt_cache_state * alloc(const server_prompt & prompt, size_t state_size_main, size_t state_size_drft,
                                      const std::string & desc = "");

    // swapped_spec: when a cached state was swapped in, set to its saved speculative carry and *swapped = true (the
    //   caller restores the carry or resets the draft side)
    bool load(server_prompt & prompt, const server_tokens & tokens_new, llama_context * ctx_tgt, llama_context * ctx_dft, int32_t id_slot,
              const std::string & desc = "", std::vector<uint8_t> * swapped_spec = nullptr, bool * swapped = nullptr);

    void update();
};

